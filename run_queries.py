"""
Step 3: run the 10 Cypher queries (cypher/q01..q10) against Aura and write
results/query_results.csv with columns: Question, Cypher Query, Answer, Execution Time.
"""
import csv
import time
from pathlib import Path

from kg.db import get_database, get_driver

ROOT = Path(__file__).parent
QUESTIONS_FILE = ROOT / "queries.txt"
CYPHER_DIR = ROOT / "cypher"
OUT_DIR = ROOT / "results"


def load_questions():
    text = QUESTIONS_FILE.read_text(encoding="utf-8-sig")
    return [q.strip() for q in text.split("\n\n") if q.strip()]


def load_query(path):
    """Return the query without leading // comment lines."""
    lines = path.read_text(encoding="utf-8").splitlines()
    return "\n".join(l for l in lines if not l.lstrip().startswith("//")).strip()


def fmt_value(v):
    if isinstance(v, list):
        return ", ".join(fmt_value(x) for x in v) if v else "-"
    if v is None:
        return "-"
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    if isinstance(v, int) and abs(v) >= 10000:
        return f"{v:,}"
    return str(v)


def fmt_answer(records):
    if not records:
        return "(no results)"
    return "\n".join(
        "; ".join(f"{k}: {fmt_value(v)}" for k, v in r.items()) for r in records
    )


def main():
    questions = load_questions()
    query_files = sorted(CYPHER_DIR.glob("q*.cypher"))
    assert len(questions) == len(query_files) == 10, (len(questions), len(query_files))

    OUT_DIR.mkdir(exist_ok=True)
    rows = []
    db = get_database()
    with get_driver() as driver:
        driver.verify_connectivity()
        for i, (question, qfile) in enumerate(zip(questions, query_files), start=1):
            query = load_query(qfile)
            with driver.session(database=db) as session:
                t0 = time.perf_counter()
                result = session.run(query)
                records = [r.data() for r in result]
                summary = result.consume()
                elapsed_ms = (time.perf_counter() - t0) * 1000
            server_ms = (summary.result_available_after or 0) + (summary.result_consumed_after or 0)
            rows.append({
                "Question": question,
                "Cypher Query": query,
                "Answer": fmt_answer(records),
                "Execution Time": f"{elapsed_ms:.2f} ms",
            })
            print(f"Q{i:02d} {qfile.name:<40} {len(records):>3} rows  "
                  f"{elapsed_ms:8.2f} ms (server {server_ms} ms)")

    csv_path = OUT_DIR / "query_results.csv"
    with csv_path.open("w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=["Question", "Cypher Query", "Answer", "Execution Time"])
        writer.writeheader()
        writer.writerows(rows)

    md = ["# Query results\n", "Generated by `run_queries.py` against Neo4j Aura.\n"]
    for i, r in enumerate(rows, start=1):
        md += [f"## Q{i}. {r['Question']}\n",
               f"```cypher\n{r['Cypher Query']}\n```\n",
               "**Answer**\n",
               "\n".join(f"- {line}" for line in r["Answer"].splitlines()) + "\n",
               f"**Execution time:** {r['Execution Time']}\n"]
    (OUT_DIR / "query_results.md").write_text("\n".join(md), encoding="utf-8")
    print(f"\nWrote {csv_path.relative_to(ROOT)} and results/query_results.md")


if __name__ == "__main__":
    main()
